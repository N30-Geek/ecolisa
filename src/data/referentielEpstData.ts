export interface CourseReference {
  code: string;
  nom: string;
  categorie:
    | 'LANGUES'
    | 'SCIENCES_EXACTES'
    | 'SCIENCES_HUMAINES'
    | 'TECHNIQUE_PROF'
    | 'EVEIL_ART'
    | 'PRATIQUE'
    | 'OPTION'
    | 'CULTURE_GENERALE';
  cycleCode: 'MATERNELLE' | 'PRIMAIRE' | 'SECONDAIRE_CTEB' | 'HUMANITES';
  optionCode?: string;
  maxScore: number;      // Max Période (ou Max Trimestre pour la Maternelle)
  maxExamen: number;     // Max Examen (Max Période x 2 pour Primaire/Secondaire, 0 pour Maternelle)
  maxSemestre: number;   // Max Semestre (Max Période x 4)
  maxAnnuel: number;     // Max Annuel (Max Période x 8 ou Max Trimestre x 3 pour Maternelle)
  coefficient: number;   // Coefficient / Poids officiel
  volumeHoraire: number; // Volume horaire hebdomadaire en heures
  groupeMaternelle?: GroupeActiviteMaternelle; // Groupe officiel pour les activités de maternelle (Groupes I à IV)
  isOptionMajora?: boolean; // Branche majeure de l'option (seuil minimum 50% obligatoire)
  ordre?: number;
}

